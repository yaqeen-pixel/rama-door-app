// Regenerates supabase/seed.sql from the JSON files in src/lib/seed.
// Usage: npm run seed:sql
import { readFileSync, writeFileSync } from "node:fs";
const read = (f) => JSON.parse(readFileSync(new URL(`../src/lib/seed/${f}`, import.meta.url)));
const q = (v) => (v == null ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a == null ? "null" : `array[${a.map((x) => (x == null ? "null" : x)).join(",")}]::integer[]`);

const creators = read("creators.json");
const sites = read("outdoor-sites.json");
const outlets = read("media-outlets.json");
const packages = read("pr-packages.json");

let sql = `-- RAMA Door seed data. Generated by scripts/generate-seed.mjs. Run after the migration.\n\n`;
sql += `insert into public.creators (id, name, nickname, rates) values\n` +
  creators.map((c) => `  (${c.id}, ${q(c.name)}, ${q(c.nickname)}, ${arr(c.rates)})`).join(",\n") +
  `\non conflict (id) do update set name = excluded.name, nickname = excluded.nickname, rates = excluded.rates;\n` +
  `select setval('public.creators_id_seq', (select max(id) from public.creators));\n\n`;
sql += `-- SAMPLE outdoor sites\ninsert into public.outdoor_sites (id, name, format, area, lat, lng, size, faces, daily_views, weekly_price, lighting) values\n` +
  sites.map((s) => `  (${s.id}, ${q(s.name)}, ${q(s.format)}, ${q(s.area)}, ${s.lat}, ${s.lng}, ${q(s.size)}, ${q(s.faces)}, ${s.dailyViews}, ${s.weeklyPrice}, ${q(s.lighting)})`).join(",\n") +
  `\non conflict (id) do nothing;\nselect setval('public.outdoor_sites_id_seq', (select max(id) from public.outdoor_sites));\n\n`;
const weeks = sites.flatMap((s) => s.bookedWeeks.map((w) => `  (${s.id}, (date_trunc('week', now()) + interval '${w + 1} week')::date)`));
if (weeks.length) sql += `-- SAMPLE booked weeks, relative to next Monday\ninsert into public.outdoor_site_weeks (site_id, week_start) values\n${weeks.join(",\n")}\non conflict do nothing;\n\n`;
sql += `-- Media outlets (real names, SAMPLE rates)\ninsert into public.media_outlets (id, name, name_ar, kind, language, about, column_cm_rate, magazine_rates, web_rates, social_rates) values\n` +
  outlets.map((o) => `  (${q(o.id)}, ${q(o.name)}, ${q(o.nameAr)}, ${q(o.kind)}, ${q(o.language)}, ${q(o.about)}, ${q(o.columnCmRate)}, ${o.magazine ? q(JSON.stringify(o.magazine)) + "::jsonb" : "null"}, ${arr(o.web)}, ${arr(o.social)})`).join(",\n") +
  `\non conflict (id) do nothing;\n\n`;
sql += `-- SAMPLE PR packages\ninsert into public.pr_packages (key, label, price, description) values\n` +
  packages.map((p) => `  (${q(p.key)}, ${q(p.label)}, ${p.price}, ${q(p.description)})`).join(",\n") + `\non conflict (key) do nothing;\n`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("Wrote supabase/seed.sql");
